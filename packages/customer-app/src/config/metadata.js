// Generate alternates for all languages
export function generateAlternates(basePath = '/') {
  const languages = ['en', 'es', 'fr', 'de', 'ar', 'he', 'hi', 'ja', 'pl', 'pt', 'ru', 'uk', 'zh'];
  const alternates = {
    canonical: basePath === '/' ? '/' : basePath,
    languages: {}
  };
  
  languages.forEach(lang => {
    if (lang === 'en') {
      alternates.languages['x-default'] = basePath;
      alternates.languages['en'] = basePath;
    } else {
      const path = basePath === '/' ? `/${lang}` : `/${lang}${basePath}`;
      alternates.languages[lang] = path;
    }
  });
  
  return alternates;
}
