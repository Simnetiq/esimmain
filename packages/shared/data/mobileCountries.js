// Helper function to detect if user is on mobile iOS device
export const isMobileIOS = () => {
  if (typeof window === 'undefined') return false;
  
  const userAgent = window.navigator.userAgent.toLowerCase();
  return /iphone|ipad|ipod/.test(userAgent) && /mobile|safari/.test(userAgent);
};

